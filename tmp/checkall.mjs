const { listVisits } = await import('../lib/notion/visits.ts')
const r = await listVisits({ fetchAll: true })
console.log('全部客情', r.items.length)
const dot = r.items.filter(v => /^[.。．、,，·•\s]/.test(v.customerName))
const yu  = r.items.filter(v => v.customerName.startsWith('與'))
console.log('點開頭', dot.length, '｜與開頭', yu.length)
const fmt = v => [v.id, v.date, v.salesperson, v.customerName, v.customerId ? '已配對' : '未配對'].join(' | ')
console.log('--- 點開頭'); dot.forEach(v=>console.log(fmt(v)))
console.log('--- 與開頭'); yu.forEach(v=>console.log(fmt(v).slice(0,120)))
