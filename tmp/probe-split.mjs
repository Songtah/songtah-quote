import { readFileSync } from 'fs'
const { getCodeNotFoundList } = await import('../lib/notion/medical-monitor.ts')
const { computeMonitor } = await import('../lib/medical-monitor-compare.ts')
const cache = JSON.parse(readFileSync('data/bas-cache.json','utf8'))
const everCodes = new Set(Object.values(cache).map(v => v.code).filter(Boolean))
const { rows } = await getCodeNotFoundList({ refresh: true })
const r = await computeMonitor()
const closureIds = new Set(r.suspectedClosures.map(x => x.customerId.replace(/-/g,'')))
const hospIds = new Set(r.hospitalUnverified.map(x => x.customerId.replace(/-/g,'')))
const everReg = rows.filter(x => everCodes.has(x.code))
console.log('查無代碼清單', rows.length)
console.log('  曾在 BAS 快取出現過（登錄過→消失）', everReg.length)
console.log('  從未出現（疑似未立案）', rows.length - everReg.length)
const byKind = (l) => l.reduce((m,x)=>((m[x.kind]=(m[x.kind]??0)+1),m),{})
console.log('  未立案的類別分布', byKind(rows.filter(x=>!everCodes.has(x.code))))
console.log('疑似歇業', r.suspectedClosures.length, '醫院待確認', r.hospitalUnverified.length)
