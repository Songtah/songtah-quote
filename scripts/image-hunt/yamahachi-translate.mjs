const idx = JSON.parse(fs.readFileSync(`${WORKSPACE}/brand-index/yamahachi.json`, 'utf8'))
let matched = 0
for (const p of idx.pages) {
  const m = p.url.match(/\/products\/([^/]+)\/?$/)
  if (!m) continue
  const slug = decodeURIComponent(m[1])
  if (DICT[slug]) { p.translatedTitle = DICT[slug]; matched++ }
}
fs.writeFileSync(`${WORKSPACE}/brand-index/yamahachi.json`, JSON.stringify(idx, null, 1))
